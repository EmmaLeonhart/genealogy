"""Build the Ono pedigree roster: every person with English and Japanese names,
Wikidata item (if any), Wikidata's own labels, family links, pedigree years and
notes. Writes genealogy/ono_roster.csv and genealogy/ono_roster.md.
Wikidata labels are cached in data_lake/downloads/wikidata/ono_roster_labels.json;
delete that file to refresh them. Run: python genealogy/make_ono_roster.py
"""
import csv
import json
import sys
import time
import urllib.parse
import urllib.request
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
import make_ono_gedcom as g  # noqa: E402

CACHE = HERE.parent / "data_lake" / "downloads" / "wikidata" / "ono_roster_labels.json"
OUT_CSV = HERE / "ono_roster.csv"
OUT_MD = HERE / "ono_roster.md"


def fetch_labels(qids):
    cache = json.loads(CACHE.read_text(encoding="utf-8")) if CACHE.exists() else {}
    missing = [q for q in qids if q not in cache]
    for i in range(0, len(missing), 40):
        url = "https://www.wikidata.org/w/api.php?" + urllib.parse.urlencode({
            "action": "wbgetentities", "ids": "|".join(missing[i:i + 40]),
            "props": "labels|descriptions", "languages": "en|ja", "format": "json"})
        req = urllib.request.Request(url, headers={"User-Agent": "INBE-research/0.1"})
        for q, e in json.load(urllib.request.urlopen(req))["entities"].items():
            cache[q] = {
                "label_en": e.get("labels", {}).get("en", {}).get("value", ""),
                "label_ja": e.get("labels", {}).get("ja", {}).get("value", ""),
                "desc_en": e.get("descriptions", {}).get("en", {}).get("value", ""),
            }
        time.sleep(1)
    CACHE.write_text(json.dumps(cache, ensure_ascii=False, indent=1), encoding="utf-8")
    return cache


def en(key):
    return g.EN[key].rstrip("?")


def year(y):
    return f"{-y} BC" if y < 0 else str(y)


labels = fetch_labels(sorted(set(g.WIKIDATA.values())))

parents, spouses, children = {}, {}, {}
for (father, mother), kids in g.families.items():
    for k in kids:
        parents[k] = [p for p in (father, mother) if p]
    if father and mother:
        spouses.setdefault(father, []).append(mother)
        spouses.setdefault(mother, []).append(father)
    for p in (father, mother):
        if p:
            children.setdefault(p, []).extend(kids)

# Gods and goddesses (命/神 of the myth layer), including the Jimmu-era ones.
GODS = {"1", "2", "W2", "3", "4", "5"} | {f"H{i}" for i in range(1, 11)}
REAL = {"21", "21b"}

rows = []
for key, p in g.people.items():
    q = g.WIKIDATA.get(key, "")
    lab = labels.get(q, {})
    d = g.DATES.get(key)
    r = g.by_seq.get(key, {})
    rows.append({
        "id": key,
        "english_name": en(key),
        "japanese_name": p["name"],
        "english_reading_uncertain": "yes" if g.EN[key].endswith("?") else "",
        "kind": ("real person" if key in REAL else "god" if key in GODS
                 else "pedigree person"),
        "role": g.ROLE.get(key, ""),
        "wikidata_qid": q,
        "wikidata_url": f"https://www.wikidata.org/wiki/{q}" if q else "",
        "wikidata_label_en": lab.get("label_en", ""),
        "wikidata_label_ja": lab.get("label_ja", ""),
        "wikidata_description_en": lab.get("desc_en", ""),
        "father_mother": "; ".join(en(x) for x in parents.get(key, [])),
        "spouse": "; ".join(en(x) for x in spouses.get(key, [])),
        "children": "; ".join(en(x) for x in children.get(key, [])),
        "years_per_pedigree": f"{year(d[0])} – {year(d[1])}" if d else "",
        "years_basis": d[2] if d else "",
        "reign_or_date_given": r.get("reign_or_date_given", ""),
        "alias_or_note": r.get("alias_or_note", "") if r else p["note"],
        "notes": r.get("notes", ""),
        "ndl_image": r.get("ndl_image", ""),
    })

with OUT_CSV.open("w", newline="", encoding="utf-8-sig") as f:
    w = csv.DictWriter(f, fieldnames=rows[0].keys())
    w.writeheader()
    w.writerows(rows)

with_q = [r for r in rows if r["wikidata_qid"]]
md = [
    "# Ono Inbe pedigree: roster",
    "",
    "Generated by `make_ono_roster.py` from the 斎部宿禰本系帳 (Ono family Inbe "
    "pedigree, 1870; NDL pid 2538213), which Kosugi Sugimura judged a Suzuki "
    "Masatoshi forgery in 1876. Full columns are in `ono_roster.csv`. "
    "\"?\" after an English name means the reading of its rare phonetic kanji is "
    "a best guess. Years are what the pedigree implies (traditional reign dates), "
    "not real dates, except for Kobito and Shikobuchi.",
    "",
    f"{len(rows)} people; {len(with_q)} have Wikidata items.",
    "",
    "| English | Japanese | Wikidata | Kind | Parents | Years (per pedigree) | Notes |",
    "|---|---|---|---|---|---|---|",
]
for r in rows:
    name = r["english_name"] + ("?" if r["english_reading_uncertain"] else "")
    qid = f"[{r['wikidata_qid']}]({r['wikidata_url']})" if r["wikidata_qid"] else ""
    note = "; ".join(x for x in [r["role"], r["alias_or_note"]] if x).replace("|", "/")
    md.append(f"| {name} | {r['japanese_name']} | {qid} | {r['kind']} | "
              f"{r['father_mother']} | {r['years_per_pedigree']} | {note} |")
OUT_MD.write_text("\n".join(md) + "\n", encoding="utf-8")
print(f"wrote {OUT_CSV} and {OUT_MD}: {len(rows)} people, {len(with_q)} with Wikidata")
