ORDER = ["duplicate", "likely-duplicate", "father-son", "half-sisters", "siblings",
         "siblings-uncertain", "different-people"]


def img(path):
    return "data:image/jpeg;base64," + base64.b64encode(Path(path).read_bytes()).decode()


def load_names():
    disp, years = collections.defaultdict(list), {}
    with open(ROOT / "reports" / "display-names.csv", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            d = (row.get("display_name") or "").strip()
            if d:
                disp[row["geni_id"]].append(d)
    with open(ROOT / "reports" / "derived-facts.csv", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            b = (row.get("birth_date_year") or "").strip()
            d = (row.get("death_date_year") or "").strip()
            if b or d:
                years[row["geni_id"]] = f"{b or '?'}&ndash;{d or '?'}"
    return disp, years


def sides(qid, disp, years):
    out = []
    for letter in ("a", "b"):
        hit = sorted(glob.glob(str(SHOTS / f"{qid}-{letter}-*.jpg")))
        if not hit:
            return None
        stem = Path(hit[0]).stem
        m = re.match(rf"{qid}-{letter}-(.*)-(\d+)$", stem)
        pretty, gid = (m.group(1).replace("-", " "), m.group(2)) if m else (stem, "")
        name = " / ".join(dict.fromkeys(disp.get(gid, []))) or pretty
        out.append((gid, name, years.get(gid, ""), hit[0]))
    return out


def card(qid, label, note, verdict, disp, years):
    s = sides(qid, disp, years)
    if not s:
        return ""
    text, cls = CHIP.get(verdict, (verdict.replace("-", " ").title(), "diff"))
    panes = "".join(
        f'<div class="side"><div class="who"><h3>{html.escape(name)[:110]}</h3>'
        f'<p class="dates">{yr}</p>'
        f'<a class="gid" href="https://www.geni.com/people/x/{gid}">{gid}</a></div>'
        f'<a class="shot" href="https://www.geni.com/people/x/{gid}">'
        f'<img loading="lazy" src="{img(path)}" alt="Geni profile page"></a></div>'
        for gid, name, yr, path in s)
    return (f'<article class="case"><header class="case-head">'
            f'<a class="qid" href="https://www.wikidata.org/wiki/{qid}">{qid}</a>'
            f'<span class="chip {cls}">{text}</span>'
            f'<p class="label">{label}</p></header>'
            f'<p class="note">{note}</p><div class="pair">{panes}</div></article>')


