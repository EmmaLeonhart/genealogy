BLURB = {
    "duplicate": "One person, two Geni profiles. The fix is a merge on Geni; the second "
                 "<code>P2600</code> on the item is then correct and stays.",
    "likely-duplicate": "Almost certainly one person, with one fact still in the way.",
    "father-son": "Two generations on one item. One <code>P2600</code> does not belong.",
    "half-sisters": "Two women on one item.",
    "siblings": "Two siblings on one item, usually sharing a name. One <code>P2600</code> does "
                "not belong.",
    "siblings-uncertain": "Read as siblings, but the name test is weak in these cases.",
    "different-people": "Two unrelated people on one item.",
}


def main():
    disp, years = load_names()
    verdicts = list(csv.DictReader(open(ROOT / "reports" / "multi-p2600-verdicts.tsv",
                                        encoding="utf-8"), delimiter="\t"))
    by = collections.defaultdict(list)
    for r in verdicts:
        by[r["verdict"]].append(r)

    body, shown = [], 0
    for v in ORDER:
        rows = by.get(v, [])
        if not rows:
            continue
        label = CHIP.get(v, (v, ""))[0]
        body.append(f'<h2>{label}<span class="n">{len(rows)}</span></h2>'
                    f'<p class="blurb">{BLURB.get(v, "")}</p>')
        for r in sorted(rows, key=lambda r: r["qid"]):
            note = html.escape(r["evidence"]).replace("&#x27;", "'")
            c = card(r["qid"], "", note, v, disp, years)
            if c:
                body.append(c)
                shown += 1

    tail = []
    for qid, (label, note) in OUT_OF_SCOPE.items():
        c = card(qid, label, note, "different-people", disp, years)
        if c:
            tail.append(c)
    if tail:
        body.append('<h2>Opened first, and outside the population'
                    f'<span class="n">{len(tail)}</span></h2>'
                    '<p class="blurb">These six were opened before the population was measured. '
                    'Wikidata carries <strong>one Geni id or none</strong> for each of them &mdash; '
                    'the second id came from our own structural walk, not from Wikidata. The Geni '
                    'evidence below is real; the claim that Wikidata held two ids was not.</p>')
        body.extend(tail)

    n_dup = len(by["duplicate"]) + len(by["likely-duplicate"])
    n_two = len(verdicts) - n_dup

    page = (
        '<title>Duplicates and Namesakes</title>\n'
        '<link rel="preconnect" href="https://fonts.googleapis.com">'
        '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
        '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?'
        'family=Newsreader:opsz,wght@6..72,400;6..72,600&'
        'family=IBM+Plex+Sans:wght@400;500;600&family=IBM+Plex+Mono:wght@400;500&display=swap">\n'
        f'<style>{CSS}</style>\n<div class="wrap"><header class="top">'
        '<h1>Duplicates and Namesakes</h1>'
        '<p class="stand">Every Wikidata item found carrying a <code>P2600</code> <em>Geni.com '
        'profile ID</em> for <strong>two different Geni profiles</strong> we hold &mdash; with '
        'both profiles opened and screenshotted, and the verdict read off the pages rather than '
        'guessed from the names.</p>'
        '<ul class="tally">'
        f'<li><b>{len(verdicts)}</b>judged</li>'
        f'<li><b>{n_dup}</b>are one person twice</li>'
        f'<li><b>{n_two}</b>are two real people</li>'
        '<li><b>70</b>in the population</li>'
        '</ul>'
        '<div class="finding"><strong>Both things happen, and the fixes are opposite.</strong> '
        'Where the two profiles are one person, Geni holds a duplicate and a merge is the answer '
        '&mdash; the second <code>P2600</code> is then correct. Where they are two people, '
        'Wikidata has joined a father to his son, two brothers, two sisters, or two strangers who '
        'share a name, and a <code>P2600</code> has to come off.'
        '<br><br><strong>The tell is a title only one person can hold.</strong> Ptolemy Apion was '
        'King of Cyrene once; Gediminas was Grand Duke once. Same office, same death year, or the '
        'same name under two alphabets means one person. Where the given names genuinely differ '
        '&mdash; Fryderyk and Fiodor, Raina and Wasylisa &mdash; they are siblings.'
        '<br><br><strong>And three of the duplicates are recorded as their own brother.</strong> '
        'Geni cannot hold one person twice without wiring the two together somehow, and sibling '
        'is what people reach for.</div>'
        '</header>\n' + "\n".join(body) +
        '\n<footer>Screenshots taken 2026-08-25 and kept in '
        '<code>Documents\\claude-screenshots\\</code>. Verdicts and their evidence live in '
        '<code>reports/multi-p2600-verdicts.tsv</code>; the population is '
        '<code>reports/multi-p2600-targets.tsv</code>, built from Wikidata&rsquo;s own '
        '<code>P2600</code> dump so every candidate is an id Wikidata actually asserts. '
        'Rebuild this page with <code>scripts/build-duplicates-artifact.py</code>. '
        'No Wikidata edit has been made or run.</footer></div>')

    dest = ROOT / "out" / "duplicates-and-namesakes.html"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(page, encoding="utf-8")
    print(f"{shown} verdict cards + {len(tail)} out-of-scope cards")
    print(f"wrote {dest}  ({dest.stat().st_size / 1024 / 1024:.2f} MB)")


if __name__ == "__main__":
    main()
